// Unit tests for the new time-field factories
// (createTimestampField, createTzField, createLocatedTimestampField).
//
// Test focus: correct field shape and locatedBy marker wiring. The actual
// TZ conversion (wall-clock ↔ UTC) is tested later at the DB-wrapper layer.

import { describe, expect, test } from "bun:test";
import { createLocatedTimestampField, createTimestampField, createTzField } from "../factories.ts";

describe("createTimestampField", () => {
  test("default form is a non-required UTC-Instant without locatedBy", () => {
    expect(createTimestampField()).toEqual({
      type: "timestamp",
      required: false,
    });
  });

  test("can be marked as required", () => {
    expect(createTimestampField({ required: true })).toEqual({
      type: "timestamp",
      required: true,
    });
  });

  test("can be marked with locatedBy (for ad-hoc cases)", () => {
    expect(createTimestampField({ locatedBy: "myTz" })).toEqual({
      type: "timestamp",
      required: false,
      locatedBy: "myTz",
    });
  });

  test("can be marked as sensitive (PII / audit protection)", () => {
    const f = createTimestampField({ sensitive: true });
    expect(f.sensitive).toBe(true);
  });
});

describe("createTzField", () => {
  test("default form is a non-required IANA-zone slot", () => {
    expect(createTzField()).toEqual({ type: "tz", required: false });
  });

  test("required + access rules apply overrides", () => {
    const f = createTzField({
      required: true,
      access: { read: ["Admin"] },
    });
    expect(f.required).toBe(true);
    expect(f.access).toEqual({ read: ["Admin"] });
  });
});

describe("createLocatedTimestampField (Phase A — atomarer Field-Type)", () => {
  test("default form is non-required with type 'locatedTimestamp'", () => {
    expect(createLocatedTimestampField()).toEqual({
      type: "locatedTimestamp",
      required: false,
    });
  });

  test("required-Override propagiert", () => {
    expect(createLocatedTimestampField({ required: true })).toEqual({
      type: "locatedTimestamp",
      required: true,
    });
  });

  test("access-Override propagiert (Field-Level Read-Access)", () => {
    const f = createLocatedTimestampField({ access: { read: ["Dispatcher"] } });
    expect(f).toEqual({
      type: "locatedTimestamp",
      required: false,
      access: { read: ["Dispatcher"] },
    });
  });

  test("sensitive-Override propagiert (PII-Schutz)", () => {
    const f = createLocatedTimestampField({ sensitive: true });
    expect(f.sensitive).toBe(true);
  });

  test("a single Field object — not a pair like the old locatedTimestamp helper", () => {
    // The new form: r.entity({ pickup: createLocatedTimestampField() })
    // produces ONE schema field (not two). The two DB columns and three API
    // fields are generated by the framework's automatic conversion.
    const field = createLocatedTimestampField();
    expect(field.type).toBe("locatedTimestamp");
    // The schema object contains no `at`/`tz`/`utc` subfields.
    expect("at" in field).toBe(false);
    expect("tz" in field).toBe(false);
  });
});
