// Provider contract for inbound-mail provider plugins.
//
// Mirrored from mail-foundation's MailTransportContext/-Plugin —
// the Foundation/provider separation and slim context are identical.
//
// **Why not a full HandlerContext?** fetch()/watch() run in the worker
// path (poll cron, IDLE supervisor), where there is no per-request
// `tx`/`actor`. A plugin that reads more would break the worker path at
// runtime, and this would only be noticed in production. Plugins that need
// more must explicitly extend InboundMailContext (a visible breaking change)
// instead of casting ctx.

import type { ConfigAccessor, Registry } from "@cosmicdrift/kumiko-framework/engine";
import type { MetricsHandle } from "@cosmicdrift/kumiko-framework/observability";
import { INBOUND_MAIL_PROVIDER_EXTENSION, type InboundMailAccountStatus } from "./constants.ts";
import type { OutboundMailMessage, OutboundMailSent } from "./outbound-mail.ts";

/**
 * Slim context for provider plugins.
 *
 * **Fields:**
 *   config   — tenant config reads (host/port/... of the plugins)
 *   registry — extension lookup in the factory (not plugin-internal)
 *   secrets  — tenant secret reads (IMAP password, OAuth refresh token)
 *   auditUserId  — audit identity for secret reads. Handler path: unset,
 *              requireSecretsContext falls back to ctx.user.id; worker/provider
 *              path: the supervisor sets the system identity.
 *   metricsFor — metrics handle of a feature by name, same behavior as
 *              HandlerContext.metricsFor: unregistered metrics are a silent
 *              no-op instead of a throw.
 */
export type InboundMailContext = {
  readonly config?: ConfigAccessor;
  readonly registry?: Registry;
  readonly secrets?: import("@cosmicdrift/kumiko-framework/secrets").SecretsContext;
  readonly auditUserId?: string | undefined;
  readonly metricsFor?: (featureName: string) => MetricsHandle;
};

/**
 * Plaintext view of a connected mailbox exposed to providers.
 * The Foundation decrypts `address` BEFORE the provider call; providers
 * never receive `kumiko-pii:` ciphertext (guard analogous to
 * withPiiCiphertextGuard in the transport path).
 */
export type MailAccountRecord = {
  /** = aggregateId of the mail-account stream and the secret-slot key. */
  readonly id: string;
  readonly tenantId: string;
  /** Provider key registered with the extension ("imap", "m365-graph",
   *  "gmail-rest"). */
  readonly provider: string;
  /** "password" | "xoauth2" | "oauth" — imap uses this to distinguish
   *  form-based connect from the XOAUTH2 fallback. */
  readonly authMethod: string;
  /** null = tenant-shared mailbox; otherwise this user's personal mailbox
   *  (visibility scope). */
  readonly ownerUserId: string | null;
  /** Postfach-Adresse, Plaintext (decrypted). */
  readonly address: string;
  readonly displayName: string;
  /** The real status; the supervisor syncs active and degraded mailboxes. */
  readonly status: InboundMailAccountStatus;
  readonly watchState: string;
};

export type RawInboundAttachment = {
  readonly fileName: string;
  readonly mimeType: string;
  readonly data: Uint8Array;
};

/** An attachment that was not stored. Carries no file name: the reason is shown to operators, not the content. */
export type SkippedInboundAttachment = {
  readonly mimeType: string;
  readonly size: number;
  readonly reason:
    | "too_large"
    | "mail_too_large"
    | "rejected"
    | "no_file_storage"
    | "nesting_too_deep";
};

/**
 * Normalized incoming mail — provider output and ingest input.
 * Provider-specific structures (IMAP flags, Graph objects) remain in the
 * provider; this type contains only the domain-level boundary.
 */
export type RawInboundMessage = {
  /** Provider-native message ID (IMAP UID, Graph id, Gmail id) — the
   *  idempotency anchor together with providerName. */
  readonly providerMessageId: string;
  /** RFC-5322 Message-ID header without <>; null when the header is missing
   *  (the Foundation falls back to a deterministic replacement). */
  readonly messageIdHeader: string | null;
  /** Provider-native thread/conversation ID when available (Graph
   *  conversationId, Gmail threadId); the Foundation prefers it over the
   *  References chain when building threadKey. */
  readonly providerThreadId: string | null;
  /** References/In-Reply-To chain (message IDs without <>), oldest first. */
  readonly references: readonly string[];
  readonly from: string;
  readonly to: readonly string[];
  readonly cc: readonly string[];
  readonly subject: string;
  /** Plaintext preview generated by the provider or truncated from the body. */
  readonly snippet: string;
  /** ISO instant — INTERNALDATE or receivedDateTime, not ingest time. */
  readonly receivedAtIso: string;
  /** Raw MIME; null when the provider has no original to keep. The Foundation persists it through
   *  file-foundation and writes bodyRef, so the event store remains blob-free. */
  readonly rawMime: Uint8Array | null;
  /** Full plaintext (derived from the HTML for HTML-only mails). Optional so providers
   *  predating the field keep compiling; the supervisor treats absent as empty. */
  readonly text?: string;
  readonly html?: string | null;
  readonly attachments?: readonly RawInboundAttachment[];
  readonly skippedAttachments?: readonly SkippedInboundAttachment[];
  /** Generic scope hint ("inbox", folder name), with no application semantics. */
  readonly scope: string;
};

/** Provider-opaker Cursor: IMAP {uidValidity,lastUid} · Graph {deltaLink}
 *  · Gmail {historyId}. Foundation persisted ihn JSON-stringified in
 *  store_mail_sync_cursors, interpretiert ihn nie. */
export type SyncCursorPayload = Readonly<Record<string, unknown>>;

/** A message the provider could not turn into a RawInboundMessage; the cursor moves past it. */
export type RejectedInboundMessage = {
  readonly providerMessageId: string;
  readonly reason: "unparseable";
};

export type InboundContentFetchResult = {
  readonly messages: readonly RawInboundMessage[];
  /** Not on the server (anymore) or from a previous UIDVALIDITY. */
  readonly missing: readonly string[];
  readonly rejected: readonly RejectedInboundMessage[];
};

export type InboundFetchResult = {
  readonly messages: readonly RawInboundMessage[];
  readonly rejected?: readonly RejectedInboundMessage[];
  readonly nextCursor: SyncCursorPayload;
  /** true ⇒ the Foundation calls fetch again in the same poll tick
   *  (pagination) until false or the maxMessages budget is exhausted. */
  readonly hasMore: boolean;
};

export type OAuthTokenSet = {
  readonly accessToken: string;
  /** ISO-Instant. TTL typisch ~1h ⇒ Foundation refresht before-poll. */
  readonly expiresAt: string;
  readonly refreshToken?: string;
  readonly scopesGranted: readonly string[];
};

/**
 * OAuth portion of the contract — OAuth providers only; imap in password
 * mode omits `oauth`. The Foundation provides the routes
 * (`/inbound-mail/connect`, `/inbound-mail/oauth/callback`) generically;
 * providers MUST NOT register their own routes.
 */
export type InboundOAuthFlow = {
  /** Scopes: request receive AND send in a SINGLE consent; re-consent is costly. */
  readonly scopes: {
    readonly receive: readonly string[];
    readonly send?: readonly string[];
  };
  readonly buildAuthorizeUrl: (
    ctx: InboundMailContext,
    p: { readonly state: string; readonly redirectUri: string },
  ) => Promise<string>;
  readonly exchangeCode: (
    ctx: InboundMailContext,
    p: { readonly code: string; readonly redirectUri: string },
  ) => Promise<OAuthTokenSet>;
  readonly refreshAccessToken: (
    ctx: InboundMailContext,
    account: MailAccountRecord,
    refreshToken: string,
    /** The foundation aborts `signal` after a hard timeout while holding a
     *  per-account lock (a pool connection is pinned meanwhile). Providers
     *  MUST pass it to their token-endpoint fetch; the foundation awaits the
     *  provider's result and never drops a late one, because that could lose
     *  a rotated refresh token. */
    opts?: { readonly signal?: AbortSignal },
  ) => Promise<OAuthTokenSet>;
};

/**
 * Inbound-mail provider plugin contract. Each provider feature
 * (inbound-provider-imap, -m365-graph, -gmail-rest) registers an
 * implementation via `r.useExtension(INBOUND_MAIL_PROVIDER_EXTENSION,
 * "<key>", plugin)`.
 */
export type InboundMailProviderPlugin = {
  /** Credential/reachability check during the connect flow — throws a
   *  typed error (InboundAuthError, etc.) and returns no value. */
  readonly verify: (ctx: InboundMailContext, account: MailAccountRecord) => Promise<void>;
  /** Read-only liveness check for the system check; falls back to `verify`. Must not
   *  change mailbox state (no flags, no new connection side effects). */
  readonly probe?: (ctx: InboundMailContext, account: MailAccountRecord) => Promise<void>;
  /** Fetch since cursor. `cursor === null` means initial population,
   *  limited by backfillWindowDays. */
  readonly fetch: (
    ctx: InboundMailContext,
    account: MailAccountRecord,
    cursor: SyncCursorPayload | null,
    opts: {
      readonly backfillWindowDays: number;
      readonly maxMessages: number;
      /** Valid OAuth access token, minted by the foundation for accounts
       *  whose provider declares `oauth` (authMethod oauth/xoauth2). Absent
       *  for password accounts and providers without an oauth flow. */
      readonly accessToken?: string;
      /** Batch lookup of the provider message ids not yet ingested for this
       *  account (committed seen anchors; lists of any size are fine, queried in chunks). Call it after
       *  the listing/delta page and download MIME only for the returned ids.
       *  Ingest dedup stays the correctness anchor; this only saves downloads. */
      readonly filterUnknownMessageIds?: (
        providerMessageIds: readonly string[],
      ) => Promise<ReadonlySet<string>>;
    },
  ) => Promise<InboundFetchResult>;
  /** Re-downloads already imported messages that were stored as snippet only. */
  readonly fetchContent?: (
    ctx: InboundMailContext,
    account: MailAccountRecord,
    providerMessageIds: readonly string[],
    opts?: { readonly accessToken?: string },
  ) => Promise<InboundContentFetchResult>;
  /** Nur OAuth-Provider. */
  readonly oauth?: InboundOAuthFlow;
  /** Sends from the mailbox address through the customer's own server. Throws
   *  MailSendNotConfiguredError, InboundAuthError, InboundTransientError or MailSendRejectedError. */
  readonly send?: (
    ctx: InboundMailContext,
    account: MailAccountRecord,
    message: OutboundMailMessage,
  ) => Promise<OutboundMailSent>;
  /** Optional live push (IMAP IDLE, later Graph/Gmail webhooks).
   *  Returns stop(). Polling remains reconciliation: watch optimizes
   *  latency but is never the correctness anchor. `onError` reports a dead
   *  live connection (drop, auth revocation) to the supervisor, which
   *  restarts it with backoff; the provider does NOT reconnect itself. */
  readonly watch?: (
    ctx: InboundMailContext,
    account: MailAccountRecord,
    handlers: {
      readonly onMessages: (msgs: readonly RawInboundMessage[]) => Promise<void>;
      readonly onError: (err: unknown) => void;
    },
    /** Same `accessToken` semantics as `fetch` opts; re-minted on every
     *  supervisor (re)start of the watch. */
    opts?: { readonly accessToken?: string },
  ) => Promise<() => Promise<void>>;
};

// `options` in the extension usage is an engine payload (unknown), so
// validate its structure instead of casting blindly (patterned after
// isMailTransportPlugin).
export function isInboundMailProviderPlugin(o: unknown): o is InboundMailProviderPlugin {
  return (
    typeof o === "object" &&
    o !== null &&
    "verify" in o &&
    typeof o.verify === "function" &&
    "fetch" in o &&
    typeof o.fetch === "function"
  );
}

// r.useExtension options-shape, co-located since the framework never imports upward.
declare module "@cosmicdrift/kumiko-framework/engine" {
  interface KumikoExtensionOptionsMap {
    [INBOUND_MAIL_PROVIDER_EXTENSION]: InboundMailProviderPlugin;
  }
}

// =============================================================================
// Typed errors handled uniformly by the Foundation during polling:
//   InboundAuthError          → status=auth_error, no retry
//   InboundRateLimitError     → abort poll, wait for the next cron tick
//   InboundCursorInvalidError → reset cursor + full resync in the backfill
//                               window; deduplication handles duplicates
//   InboundTransientError     → job retry (retries: 3, exponential)
// =============================================================================
//
// Use a `kind` discriminant instead of instanceof: plugins and the Foundation
// may run in separate bundles (dual-package-hazard), and instanceof is
// unreliable across realm or package-copy boundaries.

export class InboundAuthError extends Error {
  readonly kind = "inbound-auth-error" as const;
  constructor(message: string) {
    super(message);
    this.name = "InboundAuthError";
  }
}

/** The credential secret is not there (yet). Still an auth error for a regular poll; a sync woken
 *  right after connect treats it as "not ready" because the secret is written after the account. */
export class InboundCredentialNotStoredError extends InboundAuthError {
  readonly credentialNotStored = true as const;
  constructor(message: string) {
    super(message);
    this.name = "InboundCredentialNotStoredError";
  }
}

export class InboundRateLimitError extends Error {
  readonly kind = "inbound-rate-limit-error" as const;
  readonly retryAfterMs: number;
  constructor(message: string, retryAfterMs: number) {
    super(message);
    this.name = "InboundRateLimitError";
    this.retryAfterMs = retryAfterMs;
  }
}

export class InboundCursorInvalidError extends Error {
  readonly kind = "inbound-cursor-invalid-error" as const;
  constructor(message: string) {
    super(message);
    this.name = "InboundCursorInvalidError";
  }
}

export class InboundTransientError extends Error {
  readonly kind = "inbound-transient-error" as const;
  constructor(message: string) {
    super(message);
    this.name = "InboundTransientError";
  }
}

export function isInboundAuthError(e: unknown): e is InboundAuthError {
  return e instanceof Error && "kind" in e && e.kind === "inbound-auth-error";
}
export function isInboundCredentialNotStoredError(
  e: unknown,
): e is InboundCredentialNotStoredError {
  return isInboundAuthError(e) && "credentialNotStored" in e && e.credentialNotStored === true;
}
export function isInboundRateLimitError(e: unknown): e is InboundRateLimitError {
  return e instanceof Error && "kind" in e && e.kind === "inbound-rate-limit-error";
}
export function isInboundCursorInvalidError(e: unknown): e is InboundCursorInvalidError {
  return e instanceof Error && "kind" in e && e.kind === "inbound-cursor-invalid-error";
}
export function isInboundTransientError(e: unknown): e is InboundTransientError {
  return e instanceof Error && "kind" in e && e.kind === "inbound-transient-error";
}
