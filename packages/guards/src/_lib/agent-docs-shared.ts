import { existsSync } from "node:fs";
import { join } from "node:path";
import { Project, ts } from "ts-morph";

export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function parseJsonFile(relPath: string, raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error(`${relPath}: invalid JSON`, { cause: error });
  }
}

export function compareCodepoint(left: string, right: string): number {
  if (left < right) return -1;
  return left > right ? 1 : 0;
}

function generatedHeader(source: string): string {
  return `<!-- Generated by \`bun run gen:agent-docs\` from ${source}. Do not edit. -->`;
}

export function finishFile(source: string, body: string): string {
  const normalized = body.replace(/\r\n/g, "\n").trim();
  return `${generatedHeader(source)}\n\n${normalized}\n`;
}

function escapeCell(text: string): string {
  return text.replace(/\s+/g, " ").trim().replace(/\|/g, "\\|");
}

export function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const lines = [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`),
  ];
  return lines.join("\n");
}

export function codeList(values: readonly string[]): string {
  return values.map((value) => `\`${value}\``).join(", ");
}

const FIRST_SENTENCE_RE = /^(.+?(?<!\be\.g|\bi\.e)[.!?])(?:\s|$)/;

export function firstSentence(text: string): string {
  const flattened = text.replace(/\s+/g, " ").trim();
  return FIRST_SENTENCE_RE.exec(flattened)?.[1] ?? flattened;
}

const FALLBACK_COMPILER_OPTIONS: ts.CompilerOptions = {
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  target: ts.ScriptTarget.ES2022,
  jsx: ts.JsxEmit.ReactJSX,
  allowImportingTsExtensions: true,
  noEmit: true,
};

// The repo tsconfig carries the workspace `paths`, so re-exports from sibling
// packages resolve to their sources instead of a published dist.
export function createAgentDocsProject(repoRoot: string): Project {
  const tsConfigFilePath = join(repoRoot, "tsconfig.json");
  if (!existsSync(tsConfigFilePath)) {
    return new Project({ compilerOptions: FALLBACK_COMPILER_OPTIONS });
  }
  return new Project({
    tsConfigFilePath,
    skipAddingFilesFromTsConfig: true,
    compilerOptions: { jsx: ts.JsxEmit.ReactJSX, noEmit: true },
  });
}
