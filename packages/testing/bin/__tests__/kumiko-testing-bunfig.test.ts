// kumiko-framework#3120: `kumiko-testing bunfig` used to overwrite an
// existing bunfig.toml unconditionally, silently dropping app-owned sections
// (e.g. `[install.scopes]` with a private-registry token) and unmanaged keys
// (e.g. `concurrency`) alike. Foreign sections now merge back in verbatim;
// only an unmanaged key inside a *managed* section still blocks the write.

import { describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { main } from "../kumiko-testing";

async function runCli(args: string[], cwd: string) {
  let stdout = "";
  let stderr = "";
  const exitCode = await main(args, {
    cwd,
    stdout: (line) => {
      stdout += `${line}\n`;
    },
    stderr: (line) => {
      stderr += `${line}\n`;
    },
  });
  return { stdout, stderr, exitCode };
}

describe("kumiko-testing bunfig — existing file with a foreign section", () => {
  test("merges [install.scopes] back in instead of dropping it", async () => {
    const dir = mkdtempSync(join(tmpdir(), "kumiko-testing-bunfig-"));
    try {
      const existing =
        '[install.scopes]\n"@cosmicdriftgamestudio" = { token = "$GITHUB_TOKEN" }\n\n[test]\npreload = []\n';
      writeFileSync(join(dir, "bunfig.toml"), existing);

      const { exitCode } = await runCli(["bunfig"], dir);

      expect(exitCode).toBe(0);
      const written = readFileSync(join(dir, "bunfig.toml"), "utf-8");
      expect(written).toContain("Generated by kumiko-testing");
      expect(written).toContain(
        '[install.scopes]\n"@cosmicdriftgamestudio" = { token = "$GITHUB_TOKEN" }',
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  test("aborts and names an unmanaged key inside [test], leaves the file untouched", async () => {
    const dir = mkdtempSync(join(tmpdir(), "kumiko-testing-bunfig-"));
    try {
      const existing = "[test]\nconcurrency = 8\npreload = []\n";
      writeFileSync(join(dir, "bunfig.toml"), existing);

      const { exitCode, stderr } = await runCli(["bunfig"], dir);

      expect(exitCode).toBe(1);
      expect(stderr).toContain("test.concurrency");
      expect(readFileSync(join(dir, "bunfig.toml"), "utf-8")).toBe(existing);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  test("regenerates a file with no foreign sections and no unmanaged keys", async () => {
    const dir = mkdtempSync(join(tmpdir(), "kumiko-testing-bunfig-"));
    try {
      writeFileSync(join(dir, "bunfig.toml"), "[test]\npreload = []\n");

      const { exitCode } = await runCli(["bunfig"], dir);

      expect(exitCode).toBe(0);
      expect(readFileSync(join(dir, "bunfig.toml"), "utf-8")).toContain(
        "Generated by kumiko-testing",
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
