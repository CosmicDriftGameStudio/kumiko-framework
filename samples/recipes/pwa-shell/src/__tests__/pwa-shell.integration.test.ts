import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { createKumikoServer, type KumikoServerHandle } from "@cosmicdrift/kumiko-dev-server";
import { notesFeature, pwa } from "../app";

let handle: KumikoServerHandle;

beforeAll(async () => {
  handle = await createKumikoServer({
    features: [notesFeature],
    port: 0,
    installSignalHandlers: false,
    pwa,
  });
});

afterAll(async () => {
  await handle.stop();
});

const get = (path: string) => handle.fetch(new Request(`http://localhost${path}`));

describe("pwa-shell recipe", () => {
  test("every app route serves the shell with manifest, theme color and worker meta", async () => {
    const html = await (await get("/notes/42")).text();
    expect(html).toContain('<link rel="manifest" href="/manifest.webmanifest" />');
    expect(html).toContain('<meta name="theme-color" content="#14532d" />');
    expect(html).toContain('<link rel="apple-touch-icon" href="/icons/icon-512.png" />');
    expect(html).toContain('<meta name="kumiko-pwa-sw" content="/sw.js" />');
  });

  test("the manifest is built from the option", async () => {
    const res = await get("/manifest.webmanifest");
    expect(res.headers.get("content-type")).toBe("application/manifest+json");
    expect(await res.json()).toMatchObject({
      name: "Field Notes",
      short_name: "Notes",
      display: "standalone",
      start_url: "/",
    });
  });

  test("the worker is generated by the server and keeps /api out of its cache", async () => {
    const res = await get("/sw.js");
    expect(res.headers.get("cache-control")).toBe("no-cache");
    const script = await res.text();
    expect(script).toContain("kumiko-pwa-");
    expect(script).toContain('"/api/"');
  });
});
